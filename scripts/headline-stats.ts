/** Generates docs/submission/headline-stats.md from the live DB (numbers for the pitch, timestamped). */
import { writeFileSync } from "node:fs";
import { listProtocols, listEvents, sql, repoRootPath } from "./stats-lib";
import { fmtDuration, isOnCurve, type ControlSnapshot, type AdminFacts } from "@overwatch/core";

const rows = (await listProtocols()).filter((p) => p.source !== "demo");
const snaps = rows.map((p) => ({ p, s: p.snapshot as ControlSnapshot | null }));
const single = snaps.filter(({ s }) => s?.programs.some((x) => x.authorityKind === "SINGLE_KEY"));
const noTl = snaps.filter(({ s }) => s?.multisigs.some((m) => m.timeLockSec === 0));
const le2NoDelay = snaps.filter(({ s }) => s?.programs.some((x) => x.authorityKind === "SINGLE_KEY") || s?.multisigs.some((m) => m.timeLockSec === 0 && m.threshold <= 2));
const unmapped = snaps.filter(({ p }) => p.score && (BigInt(p.score.flags) & (1n << 9n)) !== 0n);
const lt24 = snaps.filter(({ s }) => s?.multisigs.some((m) => m.timeLockSec > 0 && m.timeLockSec < 86400));
const adminSingle = snaps.filter(({ s }) => (s?.admin as AdminFacts[] | undefined)?.some((a) => a.admin && isOnCurve(a.admin)));
const tvl = (xs: typeof snaps) => xs.reduce((n, { p }) => n + (p.tvlUsd ?? 0), 0);
const usd = (n: number) => `$${(n / 1e9).toFixed(2)}B`;
const evs = await listEvents({ limit: 1000 });
const crit = evs.filter(({ e }) => e.severity === "CRITICAL" && e.source !== "demo").length;
const now = new Date().toISOString();

const md = `# Headline stats

_Auto-generated by \`pnpm stats\` from the Overwatch database at **${now}**. Source data: Solana mainnet (read-only), decoded live. TVL is from DefiLlama (display only)._

| Stat | Value |
|---|---|
| Protocols watched (mainnet) | **${rows.length}** (${usd(tvl(snaps))} combined TVL) |
| Changeable by ≤2 people with no delay | **${le2NoDelay.length} of ${rows.length}** (${le2NoDelay.map(({ p }) => p.name).join(", ") || "none"}) |
| Upgradeable by a single private key | **${single.length}** (${single.map(({ p }) => p.name).join(", ") || "none"}) |
| Multisig with **no timelock** | **${noTl.length}** (${noTl.map(({ p }) => p.name).join(", ") || "none"}), ${usd(tvl(noTl))} TVL |
| Timelock under 24h | **${lt24.length}** (${lt24.map(({ p }) => `${p.name} ${fmtDuration(Math.min(...p.snapshot!.multisigs.map((m: { timeLockSec: number }) => m.timeLockSec)))}`).join(", ") || "none"}) |
| Control not fully mapped yet | **${unmapped.length}** (${unmapped.map(({ p }) => p.name).join(", ")}) |
| Admin key decoded as an ordinary wallet (on-curve) | ${adminSingle.map(({ p }) => p.name).join(", ") || "none"} |
| Non-demo CRITICAL events recorded | ${crit} |

## Per protocol

| Protocol | Grade | Upgrade authority | Multisig | Timelock |
|---|---|---|---|---|
${snaps.map(({ p, s }) => `| ${p.name} | ${p.score?.grade ?? "?"} ${p.score?.score ?? ""} | ${[...new Set(s?.programs.map((x) => x.authorityKind))].join(" + ")} | ${s?.multisigs.map((m) => `${m.threshold}/${m.members.length}`).join(", ") || "—"} | ${s?.multisigs.map((m) => fmtDuration(m.timeLockSec)).join(", ") || "—"} |`).join("\n")}

Drift case: the warning signs (durable nonce accounts tied to 2 of 5 signers) appeared **Mar 23, 2026**, 9 days before the Apr 1 drain (reconstructed from public incident reports; see /case/drift).
`;
writeFileSync(`${repoRootPath}/docs/submission/headline-stats.md`, md);
console.log(md);
await sql().end();
